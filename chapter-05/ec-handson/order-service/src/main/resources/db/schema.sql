CREATE TABLE M_NUMBERING (
  NUMBERING_KEY VARCHAR(20) NOT NULL PRIMARY KEY,
  PREFIX        VARCHAR(4)  NOT NULL,
  CURRENT_VALUE BIGINT      NOT NULL,
  DIGITS        INTEGER     NOT NULL
);
CREATE TABLE M_CUSTOMER (
  CUSTOMER_CODE      VARCHAR(8)    NOT NULL PRIMARY KEY,
  CUSTOMER_NAME      VARCHAR(100)  NOT NULL,
  CUSTOMER_TYPE      CHAR(1)       NOT NULL, -- 1:法人 2:個人
  CREDIT_LIMIT       NUMERIC(11,0) NOT NULL,
  RECEIVABLE_BALANCE NUMERIC(11,0) NOT NULL,
  DELETE_FLAG        CHAR(1)       NOT NULL
);
CREATE TABLE T_ORDER (
  ORDER_NO             VARCHAR(12)   NOT NULL PRIMARY KEY,
  ORDER_DATE           DATE          NOT NULL,
  CUSTOMER_CODE        VARCHAR(8)    NOT NULL,
  DELIVERY_POSTAL_CODE VARCHAR(7),
  REMARKS              VARCHAR(200),
  TOTAL_AMOUNT         NUMERIC(11,0) NOT NULL,
  ORDER_STATUS         CHAR(2)       NOT NULL, -- 10:受付 20:引当済 90:取消
  CREATED_AT           TIMESTAMP     NOT NULL,
  UPDATED_AT           TIMESTAMP     NOT NULL
);
CREATE TABLE T_ORDER_DETAIL (
  ORDER_NO     VARCHAR(12)   NOT NULL,
  LINE_NO      INTEGER       NOT NULL,
  PRODUCT_CODE VARCHAR(10)   NOT NULL,
  QUANTITY     INTEGER       NOT NULL,
  UNIT_PRICE   NUMERIC(7,0)  NOT NULL,
  AMOUNT       NUMERIC(10,0) NOT NULL,
  PRIMARY KEY (ORDER_NO, LINE_NO)
);
