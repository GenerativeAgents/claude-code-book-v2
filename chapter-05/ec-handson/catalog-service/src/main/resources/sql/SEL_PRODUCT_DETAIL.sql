-- SQL-ID: SEL_PRODUCT_DETAIL
-- 用途: CAT-001 商品照会
SELECT P.PRODUCT_CODE, P.PRODUCT_NAME, P.CATEGORY_CODE, P.UNIT_PRICE, P.SALES_STATUS,
       S.STOCK_QUANTITY - S.RESERVED_QUANTITY AS AVAILABLE_QUANTITY
FROM M_PRODUCT P
INNER JOIN M_STOCK S ON S.PRODUCT_CODE = P.PRODUCT_CODE
WHERE P.PRODUCT_CODE = ?
  AND P.DELETE_FLAG = '0'
