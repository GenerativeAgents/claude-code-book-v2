-- SQL-ID: SEL_STOCK_LOW
-- 用途: CAT-090 在庫僅少一覧バッチ（ジョブ名stock-low）
SELECT P.PRODUCT_CODE, P.PRODUCT_NAME,
       S.STOCK_QUANTITY - S.RESERVED_QUANTITY AS AVAILABLE_QUANTITY
FROM M_PRODUCT P
INNER JOIN M_STOCK S ON S.PRODUCT_CODE = P.PRODUCT_CODE
WHERE P.DELETE_FLAG = '0'
  AND P.SALES_STATUS = '1'
  AND S.STOCK_QUANTITY - S.RESERVED_QUANTITY < ?
ORDER BY P.PRODUCT_CODE
