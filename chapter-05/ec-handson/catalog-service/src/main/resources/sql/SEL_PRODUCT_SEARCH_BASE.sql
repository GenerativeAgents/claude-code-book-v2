-- SQL-ID: SEL_PRODUCT_SEARCH_BASE
-- 用途: CAT-002 商品検索（検索条件と並び順はProductSearchDaoで連結する）
SELECT P.PRODUCT_CODE, P.PRODUCT_NAME, P.CATEGORY_CODE, P.UNIT_PRICE,
       S.STOCK_QUANTITY - S.RESERVED_QUANTITY AS AVAILABLE_QUANTITY
FROM M_PRODUCT P
INNER JOIN M_STOCK S ON S.PRODUCT_CODE = P.PRODUCT_CODE
WHERE P.DELETE_FLAG = '0'
  AND P.SALES_STATUS = '1'
