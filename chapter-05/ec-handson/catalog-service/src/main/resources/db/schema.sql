-- 商品・在庫サービスのテーブル定義（テストとDockerの初期化で共用する）
CREATE TABLE M_PRODUCT (
  PRODUCT_CODE   VARCHAR(10)  NOT NULL PRIMARY KEY,
  PRODUCT_NAME   VARCHAR(100) NOT NULL,
  CATEGORY_CODE  VARCHAR(4)   NOT NULL,
  UNIT_PRICE     NUMERIC(7,0) NOT NULL,
  SALES_STATUS   CHAR(1)      NOT NULL,   -- 1:販売中 9:販売終了
  DELETE_FLAG    CHAR(1)      NOT NULL,   -- 0:有効 1:削除
  CREATED_AT     TIMESTAMP    NOT NULL,
  UPDATED_AT     TIMESTAMP    NOT NULL
);
CREATE TABLE M_STOCK (
  PRODUCT_CODE      VARCHAR(10) NOT NULL PRIMARY KEY,
  STOCK_QUANTITY    INTEGER     NOT NULL,
  RESERVED_QUANTITY INTEGER     NOT NULL,
  UPDATED_AT        TIMESTAMP   NOT NULL
);
CREATE TABLE T_RESERVATION (
  ORDER_NO           VARCHAR(12) NOT NULL,
  LINE_NO            INTEGER     NOT NULL,
  PRODUCT_CODE       VARCHAR(10) NOT NULL,
  QUANTITY           INTEGER     NOT NULL,
  RESERVATION_STATUS CHAR(1)     NOT NULL, -- 1:引当中 9:解除済
  CREATED_AT         TIMESTAMP   NOT NULL,
  UPDATED_AT         TIMESTAMP   NOT NULL,
  PRIMARY KEY (ORDER_NO, LINE_NO)
);
